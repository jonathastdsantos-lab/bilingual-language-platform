const dicts: Record<Locale, Record<TKey, string>> = { pt, en };

type Ctx = { locale: Locale; setLocale: (l: Locale) => void; t: (k: TKey) => string; dateLocale: string };
const I18nContext = createContext<Ctx | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>("pt");
  useEffect(() => {
    const saved = localStorage.getItem("sondapro.locale");
    if (saved === "pt" || saved === "en") setLocaleState(saved);
  }, []);
  useEffect(() => {
    document.documentElement.lang = locale === "pt" ? "pt-BR" : "en";
  }, [locale]);
  const setLocale = useCallback((l: Locale) => {
    setLocaleState(l);
    localStorage.setItem("sondapro.locale", l);
  }, []);
  const t = useCallback((k: TKey) => dicts[locale][k] ?? k, [locale]);
  return (
    <I18nContext.Provider value={{ locale, setLocale, t, dateLocale: locale === "pt" ? "pt-BR" : "en-US" }}>
      {children}
    </I18nContext.Provider>
  );
}

export function useT() {
  const c = useContext(I18nContext);
  if (!c) throw new Error("useT outside I18nProvider");
  return c;
}

export function formatBRL(v: number, dateLocale: string) {
  return new Intl.NumberFormat(dateLocale, { style: "currency", currency: "BRL" }).format(v);
}

export function isValidCPF(raw: string) {
  const c = raw.replace(/\D/g, "");
  if (c.length !== 11 || /^(\d)\1+$/.test(c)) return false;
  const calc = (n: number) => {
    let s = 0;
    for (let i = 0; i < n; i++) s += Number(c[i]) * (n + 1 - i);
    const r = (s * 10) % 11;
    return r === 10 ? 0 : r;
  };
  return calc(9) === Number(c[9]) && calc(10) === Number(c[10]);
}
